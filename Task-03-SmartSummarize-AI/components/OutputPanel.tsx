"use client";

import React, { useState } from "react";
import {
  Sparkles,
  Copy,
  Check,
  RotateCw,
  Trash2,
  AlertCircle,
  FileCheck2,
  TrendingDown,
  Clock,
  Bot,
  Loader2,
} from "lucide-react";
import ReactMarkdown from "react-markdown";

interface OutputPanelProps {
  summary: string;
  isStreaming: boolean;
  error: string | null;
  onRegenerate: () => void;
  onClear: () => void;
  originalTextLength: number;
}

export function OutputPanel({
  summary,
  isStreaming,
  error,
  onRegenerate,
  onClear,
  originalTextLength,
}: OutputPanelProps) {
  const [copied, setCopied] = useState(false);

  const handleCopy = async () => {
    if (!summary) return;
    try {
      await navigator.clipboard.writeText(summary);
      setCopied(true);
      setTimeout(() => setCopied(false), 2200);
    } catch (e) {
      console.error("Clipboard copy error:", e);
    }
  };

  const summaryWords = summary.trim() ? summary.trim().split(/\s+/).length : 0;
  const originalWords = originalTextLength > 0 ? Math.round(originalTextLength / 5) : 0;
  const reductionPercent =
    originalWords > 0 && summaryWords > 0
      ? Math.max(0, Math.round(((originalWords - summaryWords) / originalWords) * 100))
      : 0;

  // Approximate reading time (200 words per minute)
  const readingTimeSeconds = Math.max(5, Math.round((summaryWords / 200) * 60));

  return (
    <div className="flex flex-col h-full rounded-2xl bg-white dark:bg-navy-900 border border-slate-200 dark:border-slate-800 shadow-xl shadow-slate-200/50 dark:shadow-none p-5 sm:p-6 transition-all">
      {/* Header Bar */}
      <div className="flex items-center justify-between pb-4 border-b border-slate-100 dark:border-slate-800/80">
        <div className="flex items-center gap-2.5">
          <div className="p-2 rounded-lg bg-emerald-50 dark:bg-emerald-950/60 text-emerald-600 dark:text-emerald-400 border border-emerald-200/60 dark:border-emerald-800/40">
            <Sparkles className="w-5 h-5" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="font-bold text-lg text-slate-900 dark:text-white">
                AI Generated Summary
              </h2>
              {isStreaming && (
                <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-semibold bg-brand-500/10 text-brand-600 dark:text-brand-300 border border-brand-500/30 animate-pulse">
                  <span className="w-1.5 h-1.5 rounded-full bg-brand-500 animate-ping" />
                  Streaming
                </span>
              )}
            </div>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Distilled insights generated by Google Gemini
            </p>
          </div>
        </div>

        {/* Action Buttons */}
        {summary && (
          <div className="flex items-center gap-1.5">
            {/* Copy Button */}
            <button
              type="button"
              onClick={handleCopy}
              disabled={isStreaming}
              title="Copy summary to clipboard"
              className={`inline-flex items-center gap-1 px-3 py-1.5 text-xs font-semibold rounded-lg border transition-all ${
                copied
                  ? "bg-emerald-50 dark:bg-emerald-950/60 text-emerald-600 dark:text-emerald-400 border-emerald-300 dark:border-emerald-800"
                  : "bg-slate-50 dark:bg-slate-800 text-slate-700 dark:text-slate-200 border-slate-200 dark:border-slate-700 hover:bg-slate-100 dark:hover:bg-slate-700"
              }`}
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5" />
                  <span>Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy</span>
                </>
              )}
            </button>

            {/* Regenerate Button */}
            <button
              type="button"
              onClick={onRegenerate}
              disabled={isStreaming}
              title="Regenerate summary"
              className="inline-flex items-center gap-1 px-2.5 py-1.5 text-xs font-medium rounded-lg text-slate-600 dark:text-slate-300 hover:text-brand-600 dark:hover:text-brand-300 hover:bg-slate-100 dark:hover:bg-slate-800 border border-slate-200 dark:border-slate-700/80 disabled:opacity-50 transition-colors"
            >
              <RotateCw className={`w-3.5 h-3.5 ${isStreaming ? "animate-spin" : ""}`} />
              <span className="hidden sm:inline">Regenerate</span>
            </button>

            {/* Clear Button */}
            <button
              type="button"
              onClick={onClear}
              disabled={isStreaming}
              title="Clear summary"
              className="inline-flex items-center gap-1 px-2.5 py-1.5 text-xs font-medium rounded-lg text-rose-600 dark:text-rose-400 hover:bg-rose-50 dark:hover:bg-rose-950/40 border border-rose-200/60 dark:border-rose-900/40 disabled:opacity-50 transition-colors"
            >
              <Trash2 className="w-3.5 h-3.5" />
              <span className="hidden sm:inline">Clear</span>
            </button>
          </div>
        )}
      </div>

      {/* Main Content Area */}
      <div className="relative flex-1 mt-4 flex flex-col">
        {/* Error state */}
        {error ? (
          <div className="flex-1 flex flex-col items-center justify-center p-8 text-center rounded-xl bg-rose-50/50 dark:bg-rose-950/20 border border-rose-200 dark:border-rose-900/50">
            <div className="w-12 h-12 rounded-2xl bg-rose-100 dark:bg-rose-900/40 flex items-center justify-center text-rose-600 dark:text-rose-400 mb-3">
              <AlertCircle className="w-6 h-6" />
            </div>
            <h3 className="font-semibold text-slate-900 dark:text-white text-base mb-1">
              Summarization Failed
            </h3>
            <p className="text-xs sm:text-sm text-rose-600 dark:text-rose-300 max-w-md mb-4 leading-relaxed">
              {error}
            </p>
            <button
              type="button"
              onClick={onRegenerate}
              className="inline-flex items-center gap-1.5 px-4 py-2 rounded-xl text-xs font-semibold text-white bg-rose-600 hover:bg-rose-500 shadow-sm transition-colors"
            >
              <RotateCw className="w-3.5 h-3.5" />
              <span>Retry Generation</span>
            </button>
          </div>
        ) : summary || isStreaming ? (
          /* Active summary content or real-time streaming initialization */
          <div className="flex-1 flex flex-col">
            <div className="flex-1 min-h-[260px] sm:min-h-[300px] max-h-[500px] overflow-y-auto p-4 sm:p-5 rounded-xl bg-slate-50/70 dark:bg-navy-950/60 border border-slate-200 dark:border-slate-800 text-slate-800 dark:text-slate-100 text-sm sm:text-base leading-relaxed prose prose-sm dark:prose-invert max-w-none">
              {summary ? (
                <>
                  <ReactMarkdown>{summary}</ReactMarkdown>
                  {isStreaming && (
                    <span className="inline-block w-2 h-4 ml-1 bg-brand-500 animate-pulse align-middle" />
                  )}
                </>
              ) : (
                <div className="h-full min-h-[220px] flex flex-col items-center justify-center text-center p-8">
                  <Loader2 className="w-8 h-8 text-brand-500 animate-spin mb-3" />
                  <p className="text-sm font-semibold text-slate-800 dark:text-slate-200">
                    Connecting to Google Gemini...
                  </p>
                  <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
                    Opening real-time token stream
                  </p>
                </div>
              )}
            </div>

            {/* Summary Insights & Metrics */}
            {summary && (
              <div className="mt-4 pt-3 border-t border-slate-100 dark:border-slate-800/80 flex flex-wrap items-center justify-between gap-3 text-xs">
                <div className="flex items-center gap-4 text-slate-600 dark:text-slate-400">
                  <span className="inline-flex items-center gap-1">
                    <FileCheck2 className="w-3.5 h-3.5 text-brand-500" />
                    <span>
                      Summary: <strong className="text-slate-900 dark:text-white">{summaryWords}</strong> words
                    </span>
                  </span>

                  {reductionPercent > 0 && (
                    <span className="inline-flex items-center gap-1 text-emerald-600 dark:text-emerald-400 font-medium">
                      <TrendingDown className="w-3.5 h-3.5" />
                      <span>~{reductionPercent}% shorter</span>
                    </span>
                  )}

                  <span className="inline-flex items-center gap-1 hidden sm:inline-flex">
                    <Clock className="w-3.5 h-3.5 text-blue-500" />
                    <span>~{readingTimeSeconds}s read</span>
                  </span>
                </div>

                <span className="text-[11px] text-slate-400 dark:text-slate-500">
                  Powered by Google Gemini
                </span>
              </div>
            )}
          </div>
        ) : (
          /* Empty state */
          <div className="flex-1 min-h-[300px] flex flex-col items-center justify-center p-8 text-center rounded-xl bg-slate-50/50 dark:bg-navy-950/30 border border-dashed border-slate-200 dark:border-slate-800">
            <div className="w-14 h-14 rounded-2xl bg-gradient-to-tr from-brand-500/10 via-blue-500/10 to-cyan-500/10 dark:from-brand-500/20 dark:via-blue-500/20 dark:to-cyan-500/20 flex items-center justify-center text-brand-600 dark:text-brand-400 mb-3 border border-brand-500/20">
              <Bot className="w-7 h-7" />
            </div>
            <h3 className="font-semibold text-slate-900 dark:text-white text-base mb-1">
              No Summary Generated Yet
            </h3>
            <p className="text-xs sm:text-sm text-slate-500 dark:text-slate-400 max-w-sm mb-4 leading-relaxed">
              Paste your text in the left panel, choose your desired summary length, and click
              &quot;Generate Summary&quot; to watch real-time AI streaming.
            </p>
            <div className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-white dark:bg-slate-800/80 border border-slate-200 dark:border-slate-700/80 text-[11px] font-medium text-slate-600 dark:text-slate-300">
              <span>Tip: Click &quot;Sample Text&quot; on the left for a quick demo</span>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}

